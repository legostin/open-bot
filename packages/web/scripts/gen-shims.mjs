// Generate import-map shims for UI plugins into packages/web/public/shared/ (copied to dist/shared/ by Vite).
//
// The hub injects an import map that points "react", "react/jsx-runtime", "react-dom", "react-dom/client" and
// "@openbot/ui" at these files. Each shim re-exports the host's live instance from window.__OPENBOT_SHARED__
// (set by src/main.tsx before any UI plugin is loaded), so plugins share React with the host.
//
// Named exports are enumerated here by loading the real packages in Node; for @openbot/ui we read the keys of
// the OpenBotUIRuntime interface (and the `export declare const` values) from packages/ui-sdk/src/index.ts.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

const webDir = resolve(import.meta.dirname, "..");
const outDir = join(webDir, "public", "shared");
const require = createRequire(join(webDir, "package.json"));

// Enumerate the production build's exports (the same set the bundled host uses).
process.env.NODE_ENV = "production";

const RESERVED = new Set(
  "break case catch class const continue debugger default delete do else enum export extends false finally for function if implements import in instanceof interface let new null package private protected public return static super switch this throw true try typeof var void while with yield await".split(
    " ",
  ),
);
const isIdent = (k) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) && !RESERVED.has(k);

function shim(globalKey, moduleName, names) {
  const exported = [...new Set(names)].filter(isIdent).sort();
  return [
    `// Generated by packages/web/scripts/gen-shims.mjs. Do not edit.`,
    `// Re-exports the host's "${moduleName}" instance for UI plugins.`,
    `const shared = globalThis.__OPENBOT_SHARED__;`,
    `if (!shared || !shared.${globalKey}) throw new Error("open-bot: shared module '${moduleName}' is not initialised by the host");`,
    `const m = shared.${globalKey};`,
    `export default m;`,
    exported.length ? `export const { ${exported.join(", ")} } = m;` : "",
    "",
  ].join("\n");
}

/** Keys of `export interface OpenBotUIRuntime { ... }` plus every `export declare const X`. */
function uiRuntimeKeys() {
  const src = readFileSync(resolve(webDir, "..", "ui-sdk", "src", "index.ts"), "utf8");
  const start = src.indexOf("export interface OpenBotUIRuntime");
  if (start < 0) throw new Error("OpenBotUIRuntime not found in packages/ui-sdk/src/index.ts");
  const open = src.indexOf("{", start);
  let depth = 0;
  let end = open;
  for (; end < src.length; end++) {
    if (src[end] === "{") depth++;
    else if (src[end] === "}" && --depth === 0) break;
  }
  const keys = new Set();
  depth = 0;
  for (const raw of src.slice(open + 1, end).split("\n")) {
    const line = raw.replace(/\/\/.*$/, "");
    if (depth === 0) {
      // Top-level member: `name: ...`, `name?: ...` or `name(...)`. Comment lines start with / or *.
      const m = /^\s*([A-Za-z_$][\w$]*)\s*\??\s*[:(]/.exec(line);
      if (m) keys.add(m[1]);
    }
    for (const ch of line) {
      if (ch === "{" || ch === "(") depth++;
      else if (ch === "}" || ch === ")") depth--;
    }
  }
  for (const m of src.matchAll(/export\s+declare\s+const\s+([A-Za-z_$][\w$]*)/g)) keys.add(m[1]);
  if (keys.size === 0) throw new Error("no OpenBotUIRuntime keys found");
  return [...keys];
}

const files = {
  "react.js": shim("react", "react", Object.keys(require("react"))),
  "react-jsx-runtime.js": shim("jsxRuntime", "react/jsx-runtime", Object.keys(require("react/jsx-runtime"))),
  "react-dom.js": shim("reactDom", "react-dom", Object.keys(require("react-dom"))),
  "react-dom-client.js": shim("reactDomClient", "react-dom/client", Object.keys(require("react-dom/client"))),
  "openbot-ui.js": shim("ui", "@openbot/ui", uiRuntimeKeys()),
};

mkdirSync(outDir, { recursive: true });
for (const [name, content] of Object.entries(files)) writeFileSync(join(outDir, name), content);
console.log(`shims written to ${outDir}: ${Object.keys(files).join(", ")}`);
