// Text the macOS build generates from the installer catalogs: the two AppleScript apps, the Installer pages and the
// distribution file. Pure functions, so they are tested on any platform (packages/core/test/desktop-packaging.test.ts).

import { LOCALES, text } from "../desktop/locales.mjs";

/** Where the package puts the hub and its scripts (outside the app bundles, which then stay small and signable). */
export const SUPPORT_DIR = "/Library/Application Support/open-bot";
export const PKG_ID = "ai.openbot.pkg";
/** Node 24's own minimum. */
export const MIN_MACOS = "13.5";

/**
 * An AppleScript expression for a catalog text. The source stays ASCII (osacompile then needs no encoding): a line
 * with other characters becomes `character id {...}`, newlines `linefeed`, and `{name}` placeholders the variable
 * `p_name` (prefixed, since words like `file` are reserved in AppleScript).
 */
export function appleScriptText(s) {
  const parts = s
    .split(/(\{\w+\}|\n)/)
    .filter((piece) => piece !== "")
    .map((piece) => {
      if (piece === "\n") return "linefeed";
      if (/^\{\w+\}$/.test(piece)) return `p_${piece.slice(1, -1)}`;
      if (/^[\x20-\x7e]*$/.test(piece)) return `"${piece.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
      return `(character id {${[...piece].map((c) => c.codePointAt(0)).join(", ")}})`;
    });
  return parts.length ? parts.join(" & ") : '""';
}

const handlerName = (key) => "T_" + key.replace(/\W/g, "_");

/** One handler per message, `T_mac_ok()`, `T_mac_notStarted(file)`…, answering in Russian when `ru` is set. */
export function appleScriptMessages(catalogs, keys) {
  return keys
    .map((key) => {
      const params = [...new Set([...text(catalogs, "en", key).matchAll(/\{(\w+)\}/g)].map((m) => m[1]))];
      const lines = [`on ${handlerName(key)}(${params.map((p) => `p_${p}`).join(", ")})`];
      for (const locale of LOCALES.filter((l) => l !== "en")) {
        lines.push(`\tif ui is "${locale}" then return ${appleScriptText(text(catalogs, locale, key))}`);
      }
      lines.push(`\treturn ${appleScriptText(text(catalogs, "en", key))}`, `end ${handlerName(key)}`);
      return lines.join("\n");
    })
    .join("\n\n");
}

const PRELUDE = `-- Generated by packaging/macos/build.mjs from packaging/desktop/locales/*.json. Do not edit.
global ui

on uiLanguage()
\tset loc to user locale of (system info)
${LOCALES.filter((l) => l !== "en")
  .map((l) => `\tif loc starts with "${l}" then return "${l}"`)
  .join("\n")}
\treturn "en"
end uiLanguage
`;

const call = (key, ...args) => `my ${handlerName(key)}(${args.join(", ")})`;

/** open-bot.app: starts the hub if needed and opens it in the browser. */
export function launcherScript(catalogs) {
  return `${PRELUDE}
on run
\tset ui to uiLanguage()
\tset logFile to (POSIX path of (path to home folder)) & "Library/Application Support/open-bot/logs/hub.log"
\ttry
\t\twith timeout of 300 seconds
\t\t\tset u to do shell script "/bin/sh " & quoted form of "${SUPPORT_DIR}/bin/open.sh"
\t\tend timeout
\t\topen location u
\ton error
\t\tdisplay dialog ${call("mac.notStarted", "logFile")} buttons {${call("mac.ok")}} default button 1 with icon stop with title "open-bot"
\tend try
end run

${appleScriptMessages(catalogs, ["mac.notStarted", "mac.ok"])}
`;
}

/** Uninstall open-bot.app: asks, then removes everything in one administrator step (cancelling it changes nothing). */
export function uninstallerScript(catalogs) {
  return `${PRELUDE}
on run
\tset ui to uiLanguage()
\tset homeDir to POSIX path of (path to home folder)
\tset dataDir to homeDir & "Library/Application Support/open-bot"
\tdisplay dialog ${call("mac.uninstall.confirm")} buttons {${call("mac.uninstall.cancel")}, ${call("mac.uninstall.ok")}} default button 2 cancel button 1 with icon caution with title "open-bot"
\tset flag to ""
\tif (do shell script "if [ -d " & quoted form of dataDir & " ]; then echo yes; fi") is "yes" then
\t\tset deleteButton to ${call("mac.uninstall.deleteDataButton")}
\t\tset answer to display dialog ${call("mac.uninstall.deleteData", "dataDir")} buttons {deleteButton, ${call("mac.uninstall.keepData")}} default button 2 with icon caution with title "open-bot"
\t\tif button returned of answer is deleteButton then set flag to " --delete-data"
\tend if
\tset uid to do shell script "id -u"
\ttry
\t\tdo shell script "/bin/sh " & quoted form of "${SUPPORT_DIR}/bin/uninstall.sh" & " " & uid & " " & quoted form of homeDir & flag with administrator privileges
\ton error errText number errNum
\t\tif errNum is -128 then return
\t\tdisplay dialog ${call("mac.uninstall.failed", "errText")} buttons {${call("mac.ok")}} default button 1 with icon stop with title "open-bot"
\t\treturn
\tend try
\tdisplay dialog ${call("mac.uninstall.done")} buttons {${call("mac.ok")}} default button 1 with title "open-bot"
end run

${appleScriptMessages(catalogs, ["mac.uninstall.confirm", "mac.uninstall.cancel", "mac.uninstall.ok", "mac.uninstall.deleteDataButton", "mac.uninstall.keepData", "mac.uninstall.deleteData", "mac.uninstall.failed", "mac.uninstall.done", "mac.ok"])}
`;
}

function escapeHtml(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** An Installer page (welcome or conclusion) in one language. */
export function installerPage(catalogs, locale, page) {
  const title = text(catalogs, locale, `mac.${page}.title`);
  const body = text(catalogs, locale, `mac.${page}.body`)
    .split(/\n\n+/)
    .map((p) => `<p>${escapeHtml(p).replace(/\n/g, "<br>")}</p>`)
    .join("\n");
  return `<!doctype html>
<html lang="${locale}">
<head><meta charset="utf-8"><title>${escapeHtml(title)}</title>
<style>body { font: 13px -apple-system, "Helvetica Neue", sans-serif; } h1 { font-size: 17px; }</style></head>
<body>
<h1>${escapeHtml(title)}</h1>
${body}
</body>
</html>
`;
}

/** The productbuild distribution: one hidden choice, this Mac's startup disk only. */
export function distributionXml({ version, componentPkg }) {
  return `<?xml version="1.0" encoding="utf-8"?>
<installer-gui-script minSpecVersion="2">
  <title>open-bot</title>
  <welcome file="welcome.html" mime-type="text/html"/>
  <conclusion file="conclusion.html" mime-type="text/html"/>
  <options customize="never" require-scripts="false" hostArchitectures="arm64,x86_64"/>
  <domains enable_anywhere="false" enable_currentUserHome="false" enable_localSystem="true"/>
  <volume-check>
    <allowed-os-versions><os-version min="${MIN_MACOS}"/></allowed-os-versions>
  </volume-check>
  <choices-outline>
    <line choice="default"><line choice="${PKG_ID}"/></line>
  </choices-outline>
  <choice id="default"/>
  <choice id="${PKG_ID}" visible="false"><pkg-ref id="${PKG_ID}"/></choice>
  <pkg-ref id="${PKG_ID}" version="${version}" onConclusion="none">${componentPkg}</pkg-ref>
</installer-gui-script>
`;
}
