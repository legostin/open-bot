// Builds the Windows installer: stages the app, compiles the tray app with the .NET Framework C# compiler that ships
// with Windows, turns the installer catalogs into C# and Inno Setup messages and runs Inno Setup 6.
//   npm run package:win [-- --skip-build] [-- --skip-stage]
// Output: dist/desktop/owlbot-setup-<version>-x64.exe. Needs Inno Setup 6 (winget install JRSoftware.InnoSetup).

import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { ROOT, VERSION, removeLinks, run, stage } from "../desktop/stage.mjs";
import { LOCALES, loadCatalogs, text } from "../desktop/locales.mjs";

const HERE = import.meta.dirname;
const OUT = join(ROOT, "dist", "desktop");
const BUILD = join(OUT, "build-win");

function findTool(candidates, what) {
  const hit = candidates.filter(Boolean).find((p) => existsSync(p));
  if (!hit) throw new Error(`${what} not found (looked in ${candidates.filter(Boolean).join(", ")})`);
  return hit;
}

/** C# string literal with everything outside ASCII escaped (the compiler then needs no code page). */
function csString(s) {
  return JSON.stringify(s).replace(/[\u007f-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

function trayStrings(catalogs) {
  const dict = (locale) =>
    Object.keys(catalogs.en)
      .filter((k) => k.startsWith("tray."))
      .map((k) => `            { ${csString(k)}, ${csString(text(catalogs, locale, k))} },`)
      .join("\n");
  return `// Generated by packaging/windows/build.mjs from packaging/desktop/locales/*.json. Do not edit.
using System.Collections.Generic;
using System.Globalization;

namespace Owlbot
{
    static class L
    {
        static readonly Dictionary<string, string> En = new Dictionary<string, string>
        {
${dict("en")}
        };
        static readonly Dictionary<string, string> Ru = new Dictionary<string, string>
        {
${dict("ru")}
        };
        static readonly bool UseRu = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "ru";

        /// <summary>The message in the Windows display language (Russian or English); kv: name, value, name, value…</summary>
        public static string T(string key, params string[] kv)
        {
            string s;
            if (!(UseRu && Ru.TryGetValue(key, out s)) && !En.TryGetValue(key, out s)) s = key;
            for (int i = 0; i + 1 < kv.Length; i += 2) s = s.Replace("{" + kv[i] + "}", kv[i + 1]);
            return s;
        }
    }
}
`;
}

/** Inno Setup [CustomMessages]: dots become underscores, {name} becomes %1…, newlines %n. */
function innoMessages(catalogs) {
  const lang = { en: "english", ru: "russian" };
  const lines = ["; Generated by packaging/windows/build.mjs from packaging/desktop/locales/*.json. Do not edit.", "[CustomMessages]"];
  for (const key of Object.keys(catalogs.en).filter((k) => k.startsWith("setup."))) {
    for (const locale of LOCALES) {
      const names = [];
      const value = text(catalogs, locale, key)
        .replace(/\{(\w+)\}/g, (_, n) => {
          if (!names.includes(n)) names.push(n);
          return `%${names.indexOf(n) + 1}`;
        })
        .replace(/\r?\n/g, "%n");
      lines.push(`${lang[locale]}.${key.replace(/\./g, "_")}=${value}`);
    }
  }
  return lines.join("\r\n") + "\r\n";
}

const { values } = parseArgs({ options: { "skip-build": { type: "boolean" }, "skip-stage": { type: "boolean" } } });
const app = values["skip-stage"] ? join(OUT, "stage-win-x64", "app") : await stage({ target: "win-x64", skipBuild: !!values["skip-build"] });
if (!existsSync(join(app, "runtime", "node.exe"))) throw new Error(`no staged app in ${app}`);
mkdirSync(BUILD, { recursive: true });
const catalogs = loadCatalogs();

// Tray app.
const icon = join(ROOT, "packaging", "assets", "owlbot.ico");
const strings = join(BUILD, "Strings.g.cs");
writeFileSync(strings, trayStrings(catalogs));
const windir = process.env.SystemRoot || "C:\\Windows";
const csc = findTool([join(windir, "Microsoft.NET", "Framework64", "v4.0.30319", "csc.exe"), join(windir, "Microsoft.NET", "Framework", "v4.0.30319", "csc.exe")], "csc.exe (.NET Framework 4)");
run(csc, [
  "/nologo",
  "/target:winexe",
  "/optimize+",
  "/platform:anycpu",
  `/win32icon:${icon}`,
  `/win32manifest:${join(HERE, "tray", "owlbot.manifest")}`,
  `/out:${join(app, "Owlbot.exe")}`,
  "/r:System.Windows.Forms.dll",
  "/r:System.Drawing.dll",
  join(HERE, "tray", "OwlbotTray.cs"),
  strings,
]);
copyFileSync(icon, join(app, "owlbot.ico"));

// Installer. No links may reach it: ISCC would copy their targets into node_modules.
removeLinks(app);
const messages = join(BUILD, "messages.iss");
writeFileSync(messages, "\ufeff" + innoMessages(catalogs));
const iscc = findTool(
  [
    process.env.ISCC,
    process.env.LOCALAPPDATA && join(process.env.LOCALAPPDATA, "Programs", "Inno Setup 6", "ISCC.exe"),
    join(process.env["ProgramFiles(x86)"] || "C:\\Program Files (x86)", "Inno Setup 6", "ISCC.exe"),
    join(process.env.ProgramFiles || "C:\\Program Files", "Inno Setup 6", "ISCC.exe"),
  ],
  "Inno Setup 6 (winget install JRSoftware.InnoSetup)",
);
run(iscc, ["/Q", `/DAppVersion=${VERSION}`, `/DStageDir=${app}`, `/DOutputDir=${OUT}`, `/DMessagesFile=${messages}`, `/DIconFile=${icon}`, join(HERE, "owlbot.iss")]);
console.log(`installer: ${join(OUT, `owlbot-setup-${VERSION}-x64.exe`)}`);
